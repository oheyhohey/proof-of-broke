export type Score = keyof typeof roasts;
export function scoreForLamports(value: number): Score {
  if (!Number.isSafeInteger(value) || value < 0) throw new Error('Invalid lamports');
  if (value === 0) return 100;
  if (value < 10_000_000) return 95;
  if (value < 100_000_000) return 85;
  if (value < 1_000_000_000) return 65;
  if (value < 10_000_000_000) return 35;
  return 10;
}
export const ranks: Record<Score, string> = { 100: 'Legendary Broke', 95: 'Gas Fee Survivor', 85: 'Professional Reply Guy', 65: 'Part-Time Degen', 35: 'Financially Recovering', 10: 'Suspiciously Wealthy' };
export function hashAddress(address: string): number {
  let hash = 2166136261;
  for (const c of address) hash = Math.imul(hash ^ c.charCodeAt(0), 16777619);
  return hash >>> 0;
}
export function selectRoast(address: string, score: Score, offset = 0): string {
  const pool = roasts[score];
  return pool[(hashAddress(address) % pool.length + offset % pool.length + pool.length) % pool.length];
}
